-- Anagrafica degli indirizzi: comuni e vie in tabelle proprie, ogni via una sola volta per comune.
--
-- Solo aggiunte: indirizzo_residenza e comune_residenza restano e vengono tenuti allineati,
-- perché li leggono il client già online e get_grest_excel (che non è in questo repository).
-- Ordine di rilascio e caricamento delle righe esistenti: supabase/strumenti/indirizzi/README.md

-- Chiave di confronto: "V. Roma", "via  roma" e "VIA ROMA" sono la stessa via.
-- Da tenere allineata a normalizza() in supabase/strumenti/indirizzi/dividi_indirizzi.py.
create or replace function public.normalizza_toponimo(p_testo text)
returns text
language sql
immutable
parallel safe
set search_path = pg_catalog
as $$
  select nullif(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
    regexp_replace(
      btrim(regexp_replace(
        translate(lower(p_testo), 'àáâãäèéêëìíîïòóôõöùúûüç', 'aaaaaeeeeiiiiooooouuuuc'),
        '[^a-z0-9]+', ' ', 'g')),
      '^(v le|vle) ', 'viale '),
      '^(v lo|vlo|vic) ', 'vicolo '),
      '^v ', 'via '),
      '^(p le|ple) ', 'piazzale '),
      '^(p za|p zza|pza|pzza) ', 'piazza '),
      '^(c so|cso) ', 'corso '),
      '^(l go|lgo) ', 'largo '),
      '^str ', 'strada '),
      '^loc ', 'localita '),
      '\ms\M', 'san', 'g'),
    '')
$$;

create table if not exists public.comune (
  id_comune integer generated by default as identity primary key,
  nome text not null,
  nome_norm text generated always as (public.normalizza_toponimo(nome)) stored not null,
  constraint comune_nome_norm_key unique (nome_norm)
);

create table if not exists public.via (
  id_via integer generated by default as identity primary key,
  id_comune integer not null references public.comune(id_comune),
  nome text not null,
  nome_norm text generated always as (public.normalizza_toponimo(nome)) stored not null,
  constraint via_comune_nome_norm_key unique (id_comune, nome_norm),
  -- Destinazione della chiave composta di bambino: la via deve essere di quel comune
  constraint via_comune_id_key unique (id_comune, id_via)
);

