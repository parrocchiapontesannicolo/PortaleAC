  add constraint bambino_comune_fkey foreign key (id_comune) references public.comune(id_comune),
  add constraint bambino_via_fkey foreign key (id_comune, id_via) references public.via(id_comune, id_via),
  add constraint bambino_via_ha_comune check (id_via is null or id_comune is not null);

