create index if not exists bambino_id_via_idx on public.bambino(id_comune, id_via);

-- Trova comune e via; li aggiunge solo se non ci sono già. Security definer perché le
-- tabelle non sono scrivibili dai client: il permesso si controlla qui.
create or replace function public.risolvi_indirizzo(
  p_event_id integer, p_comune text, p_via text,
  out o_id_comune integer, out o_comune text, out o_id_via integer, out o_via text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_comune text := regexp_replace(btrim(coalesce(p_comune, '')), '\s+', ' ', 'g');
  v_via text := regexp_replace(btrim(coalesce(p_via, '')), '\s+', ' ', 'g');
begin
  if p_event_id is null or not public.has_perm(p_event_id, 'iscritti.edit') then
    raise exception 'Permesso negato' using errcode = '42501';
  end if;

  if public.normalizza_toponimo(v_comune) is null then v_comune := null; end if;
  if public.normalizza_toponimo(v_via) is null then v_via := null; end if;

  if v_via is not null and v_comune is null then
    raise exception 'Indica il comune di residenza della via %', v_via using errcode = '22023';
  end if;
  if v_comune is null then
    return;
  end if;

  insert into public.comune(nome) values (v_comune) on conflict (nome_norm) do nothing;
  select c.id_comune, c.nome into o_id_comune, o_comune
    from public.comune c
   where c.nome_norm = public.normalizza_toponimo(v_comune);

  if v_via is not null then
    insert into public.via(id_comune, nome) values (o_id_comune, v_via)
      on conflict (id_comune, nome_norm) do nothing;
    select v.id_via, v.nome into o_id_via, o_via
      from public.via v
     where v.id_comune = o_id_comune and v.nome_norm = public.normalizza_toponimo(v_via);
  end if;
end;
$$;

-- Indirizzo di un'iscrizione dal modulo. Il client nuovo manda
-- "indirizzo": {comune, via, civico}; quello vecchio solo il testo libero, che si conserva
-- com'è senza collegarlo all'anagrafica.
create or replace function public.indirizzo_da_dto(
  p_event_id integer, p_dto jsonb,
  out o_strutturato boolean, out o_id_comune integer, out o_id_via integer,
  out o_civico text, out o_indirizzo text, out o_comune text)
language plpgsql
set search_path = public
as $$
declare
  v_via text;
begin
  o_strutturato := coalesce(jsonb_typeof(p_dto->'indirizzo') = 'object', false);
  if not o_strutturato then
    o_indirizzo := p_dto->>'indirizzo_residenza';
    o_comune := p_dto->>'comune_residenza';
    return;
  end if;

  select r.o_id_comune, r.o_comune, r.o_id_via, r.o_via
    into o_id_comune, o_comune, o_id_via, v_via
    from public.risolvi_indirizzo(p_event_id, p_dto#>>'{indirizzo,comune}', p_dto#>>'{indirizzo,via}') r;

  o_civico := nullif(btrim(coalesce(p_dto#>>'{indirizzo,civico}', '')), '');
  if o_civico is not null and v_via is null then
    raise exception 'Indica la via del civico %', o_civico using errcode = '22023';
  end if;
  o_indirizzo := case when v_via is null then null
                      else v_via || coalesce(' ' || o_civico, '') end;
end;
$$;

-- Comuni e vie per i suggerimenti del modulo e per mostrare l'indirizzo di un iscritto.
-- Stessi permessi della lettura di bambino; senza permessi nessuna riga.
create or replace function public.elenco_indirizzi(p_event_id integer)
returns table(id_comune integer, comune text, id_via integer, via text)
language sql
stable
security definer
set search_path = public
as $$
  select c.id_comune, c.nome, v.id_via, v.nome
    from public.comune c
    left join public.via v on v.id_comune = c.id_comune
   where public.has_any_perm(p_event_id, array['iscritti.view', 'iscritti.edit', 'iscritti.pagamenti'])
   order by c.nome, v.nome
$$;

revoke all on function public.normalizza_toponimo(text) from public, anon;
revoke all on function public.risolvi_indirizzo(integer, text, text) from public, anon;
revoke all on function public.indirizzo_da_dto(integer, jsonb) from public, anon;
revoke all on function public.elenco_indirizzi(integer) from public, anon;
grant execute on function public.normalizza_toponimo(text) to authenticated;
grant execute on function public.risolvi_indirizzo(integer, text, text) to authenticated;
grant execute on function public.indirizzo_da_dto(integer, jsonb) to authenticated;
grant execute on function public.elenco_indirizzi(integer) to authenticated;

-- RPC di iscrizione: uguali a 20261010120000_v2_account_permessi.sql tranne l'indirizzo.

create or replace function public.create_iscrizione(p_dto jsonb)
 returns integer
 language plpgsql
 set search_path = public
as $function$
declare
    v_bambino_id integer;
    v_iscrizione_id integer;
    v_event_id integer;
    g jsonb;
    s jsonb;
    c jsonb;
    v_genitore_id integer;
    v_ind record;
begin
    v_event_id := (p_dto->>'event_id')::int;
    if v_event_id is null or not public.has_perm(v_event_id, 'iscritti.edit') then
        raise exception 'Permesso negato' using errcode = '42501';
    end if;

    -- 1. Bambino (l'indirizzo passa dall'anagrafica: via e comune nuovi vengono aggiunti solo se mancano)
    select * into v_ind from public.indirizzo_da_dto(v_event_id, p_dto);

    insert into bambino(event_id, nome, cognome, data_nascita, genere, luogo_nascita, indirizzo_residenza, comune_residenza, id_comune, id_via, civico)
    values (
        v_event_id,
        p_dto->>'nome',
        p_dto->>'cognome',
        (p_dto->>'data_nascita')::date,
        (p_dto->>'genere')::int,
        p_dto->>'luogo_nascita',
        v_ind.o_indirizzo,
        v_ind.o_comune,
        v_ind.o_id_comune,
        v_ind.o_id_via,
        v_ind.o_civico
    )
    returning id_bambino into v_bambino_id;

    -- 2. Iscrizione
    insert into iscrizione(event_id, id_bambino, anno, note, inclusa_iscrizione_noi, altra_parrocchia, modalita_pagamento, formato_iscrizione, sconto_fratelli, ricevuta, esce_solo, caparra_pagata, priority, desc_ricevuta, email_genitore)
    values (
        v_event_id,
        v_bambino_id,
        (p_dto->>'anno_scolastico')::int,
        p_dto->>'note',
        (p_dto->>'da_iscrivere_al_noi')::boolean,
        (p_dto->>'altra_parrocchia')::boolean,
        (p_dto->>'modalita_pagamento')::int,
        (p_dto->>'formato_iscrizione')::int,
        (p_dto->>'sconto_fratelli')::boolean,
        (p_dto->>'ricevuta')::boolean,
        (p_dto->>'esce_solo')::boolean,
        (p_dto->>'caparra_pagata')::boolean,
        (p_dto->>'priority')::boolean,
        (p_dto->>'desc_ricevuta'),
        (p_dto->>'email_genitore')
    )
    returning id_iscrizione into v_iscrizione_id;

    -- 3. Genitori e collegamenti
    if jsonb_typeof(p_dto->'genitori') = 'array' then
        for g in select * from jsonb_array_elements(p_dto->'genitori') loop
            v_genitore_id := null;

            if (g->>'id_genitore') is not null then
                select id_genitore into v_genitore_id
                  from genitore
                 where id_genitore = (g->>'id_genitore')::int;

                if v_genitore_id is null then
                    raise exception 'Genitore con Id % non trovato', g->>'id_genitore';
                end if;

                update genitore
                   set nome = coalesce(g->>'nome', nome),
                       cognome = coalesce(g->>'cognome', cognome),
                       telefono = coalesce(g->>'telefono', telefono),
                       sesso = coalesce((g->>'sesso')::int, sesso)
                 where id_genitore = v_genitore_id;
            else
                insert into genitore(event_id, nome, cognome, telefono, sesso)
                values (v_event_id, g->>'nome', g->>'cognome', g->>'telefono', (g->>'sesso')::int)
                returning id_genitore into v_genitore_id;
            end if;

            insert into genitore_bambino(event_id, id_genitore, id_bambino)
            values (v_event_id, v_genitore_id, v_bambino_id)
            on conflict do nothing;
        end loop;
    end if;

    -- 4. Settimane
    if jsonb_typeof(p_dto->'settimane') = 'array' then
        for s in select * from jsonb_array_elements(p_dto->'settimane') loop
            insert into iscrizione_settimana(event_id, id_iscrizione, id_settimana, intero)
            values (v_event_id, v_iscrizione_id, (s->>'id_settimana')::int, (s->>'intero')::boolean)
            on conflict do nothing;
        end loop;
    end if;

    -- 5. Taglia
    if (p_dto->>'Taglia') is not null then
        insert into iscrizione_taglia(event_id, id_iscrizione, id_taglia)
        values (v_event_id, v_iscrizione_id, (p_dto->>'Taglia')::int)
        on conflict do nothing;
    end if;

    -- 6. Scheda sanitaria
    insert into scheda_sanitaria(event_id, id_iscrizione, allergie_intolleranze, patologie_terapie)
    values (v_event_id, v_iscrizione_id, p_dto->>'allergie_intolleranze', p_dto->>'patologie_terapie');

    -- 7. Consensi
    if jsonb_typeof(p_dto->'consensi') = 'array' then
        for c in select * from jsonb_array_elements(p_dto->'consensi') loop
            if (c->>'id_tipo_consenso') is not null then
                insert into consenso(event_id, id_iscrizione, id_tipo_consenso, valore)
                values (v_event_id, v_iscrizione_id, (c->>'id_tipo_consenso')::int, (c->>'valore')::boolean)
                on conflict do nothing;
            end if;
        end loop;
    end if;

    return v_bambino_id;
end;
$function$;

create or replace function public.update_iscrizione(p_dto jsonb, p_id_bambino integer)
 returns integer
 language plpgsql
 set search_path = public
as $function$
declare
    v_bambino_id integer := p_id_bambino;
    v_iscrizione_id integer;
    v_event_id integer;
    v_genitore_id integer;
    g jsonb;
    s jsonb;
    c jsonb;
    v_ind record;
begin
    v_event_id := (p_dto->>'event_id')::int;
    if v_event_id is null or not public.has_perm(v_event_id, 'iscritti.edit') then
        raise exception 'Permesso negato' using errcode = '42501';
    end if;
    if not public.bambino_in_evento(v_bambino_id, v_event_id) then
        raise exception 'Iscritto % non trovato in questo evento', v_bambino_id;
    end if;

    -- 1. Bambino
    select * into v_ind from public.indirizzo_da_dto(v_event_id, p_dto);

    update bambino
       set nome = coalesce(p_dto->>'nome', nome),
           cognome = coalesce(p_dto->>'cognome', cognome),
           data_nascita = coalesce(p_dto->>'data_nascita', data_nascita),
           genere = coalesce(nullif(p_dto->>'genere', '')::int, genere),
           luogo_nascita = coalesce(p_dto->>'luogo_nascita', luogo_nascita),
           indirizzo_residenza = case when v_ind.o_strutturato then v_ind.o_indirizzo
                                      else coalesce(v_ind.o_indirizzo, indirizzo_residenza) end,
           comune_residenza = case when v_ind.o_strutturato then v_ind.o_comune
                                   else coalesce(v_ind.o_comune, comune_residenza) end,
           -- Client vecchio: il testo cambiato non corrisponde più all'anagrafica, il
           -- collegamento si azzera e la riga torna tra quelle da sistemare.
           id_comune = case when v_ind.o_strutturato then v_ind.o_id_comune
                            when coalesce(v_ind.o_comune, comune_residenza) is distinct from comune_residenza then null
                            else id_comune end,
           id_via = case when v_ind.o_strutturato then v_ind.o_id_via
                         when coalesce(v_ind.o_comune, comune_residenza) is distinct from comune_residenza
                           or coalesce(v_ind.o_indirizzo, indirizzo_residenza) is distinct from indirizzo_residenza then null
                         else id_via end,
           civico = case when v_ind.o_strutturato then v_ind.o_civico
                         when coalesce(v_ind.o_comune, comune_residenza) is distinct from comune_residenza
                           or coalesce(v_ind.o_indirizzo, indirizzo_residenza) is distinct from indirizzo_residenza then null
                         else civico end
     where id_bambino = v_bambino_id;

    -- 2. Iscrizione
    select id_iscrizione into v_iscrizione_id
      from iscrizione
     where id_bambino = v_bambino_id;

    if v_iscrizione_id is null then
        raise exception 'Iscrizione per bambino % non trovata', v_bambino_id;
    end if;

    -- 3. Dati iscrizione
    update iscrizione
       set anno = coalesce(nullif(p_dto->>'anno_scolastico', '')::int, anno),
           note = coalesce(p_dto->>'note', note),
           inclusa_iscrizione_noi = coalesce((p_dto->>'da_iscrivere_al_noi')::boolean, inclusa_iscrizione_noi),
           altra_parrocchia = coalesce((p_dto->>'altra_parrocchia')::boolean, altra_parrocchia),
           modalita_pagamento = coalesce(nullif(p_dto->>'modalita_pagamento', '')::int, modalita_pagamento),
           formato_iscrizione = coalesce(nullif(p_dto->>'formato_iscrizione', '')::int, formato_iscrizione),
           sconto_fratelli = coalesce((p_dto->>'sconto_fratelli')::boolean, sconto_fratelli),
           ricevuta = coalesce((p_dto->>'ricevuta')::boolean, ricevuta),
           esce_solo = coalesce((p_dto->>'esce_solo')::boolean, esce_solo),
           caparra_pagata = coalesce((p_dto->>'caparra_pagata')::boolean, caparra_pagata),
           priority = coalesce((p_dto->>'priority')::boolean, priority),
           desc_ricevuta = coalesce((p_dto->>'desc_ricevuta'), desc_ricevuta),
           email_genitore = coalesce((p_dto->>'email_genitore'), email_genitore)
     where id_iscrizione = v_iscrizione_id;

    -- 4. Genitori: toglie solo i collegamenti non più presenti nel modulo
    if jsonb_typeof(p_dto->'genitori') = 'array' then
        delete from genitore_bambino
         where id_bambino = v_bambino_id
           and id_genitore not in (
             select (x->>'id_genitore')::int
               from jsonb_array_elements(p_dto->'genitori') x
              where nullif(x->>'id_genitore', '') is not null);

        for g in select * from jsonb_array_elements(p_dto->'genitori') loop
            v_genitore_id := null;

            if nullif(g->>'id_genitore', '') is not null then
                select id_genitore into v_genitore_id
                  from genitore
                 where id_genitore = (g->>'id_genitore')::int;

                if v_genitore_id is null then
                    raise exception 'Genitore con Id % non trovato', g->>'id_genitore';
                end if;

                update genitore
                   set nome = coalesce(g->>'nome', nome),
                       cognome = coalesce(g->>'cognome', cognome),
                       telefono = coalesce(g->>'telefono', telefono),
                       sesso = coalesce(nullif(g->>'sesso', '')::int, sesso)
                 where id_genitore = v_genitore_id;
            else
                insert into genitore(event_id, nome, cognome, telefono, sesso)
                values (v_event_id, g->>'nome', g->>'cognome', g->>'telefono', nullif(g->>'sesso', '')::int)
                returning id_genitore into v_genitore_id;
            end if;

            insert into genitore_bambino(event_id, id_genitore, id_bambino)
            values (v_event_id, v_genitore_id, v_bambino_id)
            on conflict do nothing;
        end loop;
    end if;

    -- 5. Settimane
    if jsonb_typeof(p_dto->'settimane') = 'array' then
        delete from iscrizione_settimana where id_iscrizione = v_iscrizione_id;

        for s in select * from jsonb_array_elements(p_dto->'settimane') loop
            insert into iscrizione_settimana(event_id, id_iscrizione, id_settimana, intero)
            values (v_event_id, v_iscrizione_id, (s->>'id_settimana')::int, (s->>'intero')::boolean)
            on conflict do nothing;
        end loop;
    end if;

    -- 6. Taglia
    if (p_dto->>'taglia') is not null then
        delete from iscrizione_taglia where id_iscrizione = v_iscrizione_id;

        insert into iscrizione_taglia(event_id, id_iscrizione, id_taglia)
        values (v_event_id, v_iscrizione_id, (p_dto->>'taglia')::int)
        on conflict do nothing;
    end if;

    -- 7. Scheda sanitaria
    if p_dto ? 'allergie_intolleranze' or p_dto ? 'patologie_terapie' then
        insert into scheda_sanitaria(event_id, id_iscrizione, allergie_intolleranze, patologie_terapie)
        values (v_event_id, v_iscrizione_id, p_dto->>'allergie_intolleranze', p_dto->>'patologie_terapie')
        on conflict (id_iscrizione) do update
        set allergie_intolleranze = excluded.allergie_intolleranze,
            patologie_terapie = excluded.patologie_terapie;
    end if;

    -- 8. Consensi
    if jsonb_typeof(p_dto->'consensi') = 'array' then
        delete from consenso where id_iscrizione = v_iscrizione_id;

        for c in select * from jsonb_array_elements(p_dto->'consensi') loop
            insert into consenso(event_id, id_iscrizione, id_tipo_consenso, valore)
            values (v_event_id, v_iscrizione_id, (c->>'id_tipo_consenso')::int, (c->>'valore')::boolean)
            on conflict do nothing;
        end loop;
    end if;

    return v_iscrizione_id;
end;
$function$;

